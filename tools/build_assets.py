"""Build SQLite statement bundles for sqflite; never split trigger SQL on semicolons."""
import hashlib
import json
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def statements(source):
    current = ''
    for line in source.splitlines(keepends=True):
        current += line
        if sqlite3.complete_statement(current):
            yield current.strip()
            current = ''
    if current.strip() and any(not s.strip().startswith('--') for s in current.splitlines() if s.strip()):
        raise ValueError('Incomplete SQL statement')

def bundle(path):
    content = path.read_text(encoding='utf-8')
    return {'name':path.name,'sha256':hashlib.sha256(content.encode()).hexdigest(),'statements':list(statements(content))}

def main():
    migrations = [dict(version=i+1,**bundle(p)) for i,p in enumerate(sorted((ROOT/'database/migrations').glob('*.sql')))]
    seeds = {p.stem:bundle(p) for p in sorted((ROOT/'database/seeds').glob('*.sql'))}
    output = ROOT/'app/assets/database.json'
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps({'migrations':migrations,'seeds':seeds},ensure_ascii=False,indent=2)+'\n')
    schema = '-- Generated by tools/build_assets.py. New databases only; use the migration runner for upgrades.\nPRAGMA foreign_keys=ON;\nBEGIN IMMEDIATE;\n'
    schema += '\n'.join(p.read_text() for p in sorted((ROOT/'database/migrations').glob('*.sql')))
    schema += '\n' + (ROOT/'database/seeds/production.sql').read_text()
    schema += '\nCREATE TABLE SchemaMigrations(Version INTEGER PRIMARY KEY,Name TEXT NOT NULL,Checksum TEXT NOT NULL);\n'
    for migration in migrations:
        schema += f"INSERT INTO SchemaMigrations VALUES({migration['version']},'{migration['name']}','{migration['sha256']}');\n"
    schema += f"PRAGMA user_version={len(migrations)};\nCOMMIT;\n"
    (ROOT/'database/schema.sql').write_text(schema)

if __name__=='__main__':
    main()
